const GROUP_SORT_ORDER: Record<string, number> = {
  overview: 10,
  iam: 15,
  security: 25,
  restaurant: 20,
  'employee-meal': 22,
  system: 30,
};

export async function seedResources(db: SeedClient): Promise<Permission[]> {
  const permissions: Permission[] = [];

  for (const item of PLATFORM_RESOURCES) {
    const resource = await db.resource.upsert({
      where: { slug: item.slug },
      create: {
        slug: item.slug,
        name: item.name,
        description: item.name,
        scope: PermissionScope.PLATFORM,
        path: item.path,
        icon: item.icon,
        groupKey: item.groupKey,
        groupLabel: item.groupLabel,
        groupSortOrder: GROUP_SORT_ORDER[item.groupKey] ?? 0,
        sortOrder: item.sortOrder,
        isSystem: true,
        isMenu: item.isMenu,
        menuExact: item.menuExact,
        menuAnyOf: [...item.menuAnyOf],
      },
      update: {
        name: item.name,
        description: item.name,
        path: item.path,
        icon: item.icon,
        groupKey: item.groupKey,
        groupLabel: item.groupLabel,
        groupSortOrder: GROUP_SORT_ORDER[item.groupKey] ?? 0,
        sortOrder: item.sortOrder,
        isSystem: true,
        isMenu: item.isMenu,
        menuExact: item.menuExact,
        menuAnyOf: [...item.menuAnyOf],
        deletedAt: null,
      },
    });

    for (const action of item.actions) {
      const key = `platform:${item.slug}:${action.action}`;
      permissions.push(
        await db.permission.upsert({
          where: { key },
          create: {
            key,
            name: action.name,
            description: action.name,
            resource: item.slug,
            action: action.action,
            scope: PermissionScope.PLATFORM,
            isDangerous: action.isDangerous,
            resourceId: resource.id,
          },
          update: {
            name: action.name,
            description: action.name,
            resource: item.slug,
            action: action.action,
            scope: PermissionScope.PLATFORM,
            isDangerous: action.isDangerous,
            resourceId: resource.id,
          },
        }),
      );
    }
  }

  await db.resource.updateMany({
    where: {
      slug: {
        in: [
          'price-lists',
          'menu-item-prices',
          'payment-providers',
          'payment-methods',
        ],
      },
    },
    data: { isMenu: false, deletedAt: new Date() },
  });

  const deprecatedKeys = [
    'platform:users:write',
    'platform:organizations:write',
  ];

  await db.permission.deleteMany({
    where: { key: { in: deprecatedKeys } },
  });

  return permissions;
}
